#!/usr/bin/env python3
"""Generate the draft SDK surface. No transport IDs are defined here."""
import argparse
import json
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / 'src/Nexa.Plugin.Sdk.Abi100'
spec = json.loads((ROOT / 'contracts/abi100.json').read_text())
header = '// <auto-generated />\n#nullable enable\nusing System.Collections.Immutable;\nusing Nexa.Plugin.Bootstrap.V1;\n'
primitive = {'string':'String','bool':'Boolean','long':'Int64','ulong':'UInt64','double':'Float64','Guid':'Guid','DateTimeOffset':'Timestamp','AbiValue':'Value'}

def typ(t):
    if t.endswith('[]'): return f'ImmutableArray<{typ(t[:-2])}>'
    if t.endswith('?'): return typ(t[:-1])+'?'
    if '<' in t:
        a,b=t.split('<',1); return f'global::Nexa.Plugin.Sdk.Abi100.Data.{a}<{typ(b[:-1])}>'
    return t if t in primitive else 'global::Nexa.Plugin.Sdk.Abi100.Data.'+t

nullable_counter = 0

def codec(t, value, write):
    global nullable_counter
    action='Write' if write else 'Read'
    if t.endswith('?'):
        inner=t[:-1]
        if write:
            nullable_counter += 1
            local = f"present{nullable_counter}"
            return f'({value} is {{ }} {local} ? {codec(inner,local,True)} : new AbiValue.Null())'
        return f'({value} is AbiValue.Null ? null : {codec(inner,value,False)})'
    if t.endswith('[]'):
        return f'DataCodec.{action}Array({value}, (item, nestedDepth) => {codec(t[:-2],"item",write).replace("depth + 1", "nestedDepth")}, depth + 1)'
    if t in primitive: return f'DataCodec.{action}{primitive[t]}({value})'
    if t in spec['enums']:
        return f'DataCodec.{action}Enum({value})' if write else f'DataCodec.ReadEnum<{typ(t)}>({value})'
    return f'{typ(t)}.{action}({value}, depth + 1)'

models = header+'namespace Nexa.Plugin.Sdk.Abi100.Data;\n\n'
for name,values in spec['enums'].items(): models += f'public enum {name} {{ '+', '.join(values)+' }\n'
for name,fields in spec['models'].items():
    models += f'\npublic sealed record {name}('+', '.join(f'{typ(f["type"])} {f["name"]}' for f in fields)+f') : IAbiData<{name}>\n{{\n'
    models += f'    public static AbiValue Write({name} value, int depth = 0)\n    {{\n        using var scope = DataCodec.Enter(depth);\n        ArgumentNullException.ThrowIfNull(value);\n        return DataCodec.Map('
    models += ', '.join(f'("{f["name"][0].lower()+f["name"][1:]}", {codec(f["type"],"value."+f["name"],True)})' for f in fields)+');\n    }\n'
    models += f'    public static {name} Read(AbiValue value, int depth = 0)\n    {{\n        using var scope = DataCodec.Enter(depth);\n        var map = DataCodec.ReadMap(value);\n        return new('
    models += ', '.join(codec(f['type'],f'DataCodec.Field(map, "{f["name"][0].lower()+f["name"][1:]}")',False) for f in fields)+');\n    }\n}\n'

apis = header+'namespace Nexa.Plugin.Sdk.Abi100;\n\n'
existing={'Events100','Ui100','InterPlugin100','Diagnostics100','Resources100'}
seen=set()
for g in spec['groups']:
    name=g['className']
    apis += f'public sealed partial class {name}'+('' if name in existing else '(IAbilityV1 ability)')+f' : ICapabilityView<{name}>\n{{\n'
    if name not in existing: apis+= f'    public const string ContractId = "{g["contractId"]}";\n'
    apis += f'    public static string CapabilityId => ContractId;\n    public static {name} Create(IAbilityV1 port) => new(port);\n'
    for op in g['operations']:
        key=(g['contractId'],op['methodId'])
        if key in seen: raise ValueError(f'Duplicate dispatch slot: {key}')
        seen.add(key)
        apis+=f'    /// <summary>{op["kind"]}; host support is versioned in host-support.json. See Abi100Catalog for authority and phase requirements.</summary>\n'
        apis+=f'    public ValueTask<AbiReply<{typ(op["output"])}>> {op["name"]}({typ(op["input"])} request, InvocationOptions options) =>\n        AbiContractCall.Invoke<{typ(op["input"])}, {typ(op["output"])}>(ability, ContractId, {op["methodId"]}, request, options);\n'
    apis+='}\n\n'

context=header+'namespace Nexa.Plugin.Sdk.Abi100;\n\npublic sealed partial class Abi100Context\n{\n'
new=[g for g in spec['groups'] if g['className'] not in existing and '.' not in g['name']]
for g in new: context+=f'    public {g["className"]} {g["name"]} {{ get; private set; }} = null!;\n'
context+='    public Minecraft100 Minecraft { get; private set; } = null!;\n    private void InitializePublicGroups()\n    {\n'
for g in new: context+=f'        {g["name"]} = new(new ContextAbility(this, {g["className"]}.ContractId));\n'
context+='        Minecraft = new(contract => new ContextAbility(this, contract));\n    }\n}\n\npublic sealed class Minecraft100\n{\n'
mc=[g for g in spec['groups'] if g['name'].startswith('Minecraft.')]
for g in mc: context+=f'    public {g["className"]} {g["name"].split(".")[1]} {{ get; }}\n'
context+='    internal Minecraft100(Func<string, IAbilityV1> resolve)\n    {\n'
for g in mc: context+=f'        {g["name"].split(".")[1]} = new(resolve({g["className"]}.ContractId));\n'
context+='    }\n}\n'

catalog=header+'namespace Nexa.Plugin.Sdk.Abi100;\n\npublic sealed record AbiOperationDescriptor(string Group, string ContractId, uint MethodId, string Name, string Input, string Output, string Kind, ImmutableArray<string> Phases, string Permission, string Idempotency, string HostBinding);\n\npublic static class Abi100Catalog\n{\n    // SDK-local dispatch slots, not NexaCL transport opcodes.\n    public static ImmutableArray<AbiOperationDescriptor> Operations { get; } =\n    [\n'
for g in spec['groups']:
    for op in g['operations']:
        vals=[json.dumps(x) for x in [g['name'],g['contractId']]]+[str(op['methodId'])]+[json.dumps(op[k]) for k in ['name','input','output','kind']]+['['+', '.join(json.dumps(p) for p in op['phases'])+']']+[json.dumps(op[k]) for k in ['permission','idempotency']]+[json.dumps('HostDefined')]
        catalog+='        new('+', '.join(vals)+'),\n'
catalog+='    ];\n}\n'

# Each fingerprint includes the transitive model/enum closure, not unrelated models.
schemas = header + 'using Nexa.Plugin.Sdk.Abi100.Data;\nnamespace Nexa.Plugin.Sdk.Abi100;\n\npublic static class Abi100Schemas\n{\n'
schema_fingerprints = {}
schema_targets = {name: name for name in spec['models']}
for name in spec['models']:
    closure = {}; pending = [name]
    while pending:
        item = pending.pop()
        if item in closure: continue
        if item in spec['models']:
            closure[item] = spec['models'][item]
            for field in closure[item]: pending.extend(re.findall(r'[A-Za-z][A-Za-z0-9]*', field['type']))
        elif item in spec['enums']: closure[item] = spec['enums'][item]
    fingerprint = hashlib.sha256(json.dumps({'root':name,'types':closure,'codec':'nexa-abi-value-1','scalarContract':1}, sort_keys=True, separators=(',',':')).encode()).hexdigest()
    schema_fingerprints[name] = fingerprint
    schemas += f'    public static SchemaRef {name} {{ get; }} = new(new("nexa:abi100/{name.lower()}"), 1, "{fingerprint}");\n'
# Closed collection schemas are additive. Keep every existing model fingerprint unchanged.
generic_shapes = {
    'Page': [{'name':'Items','type':'T[]'}, {'name':'NextCursor','type':'string?'}, {'name':'Revision','type':'Revision'}],
    'Snapshot': [{'name':'Value','type':'T'}, {'name':'Revision','type':'Revision'}, {'name':'SchemaVersion','type':'ulong'}, {'name':'ObservedAt','type':'DateTimeOffset'}]
}
for generic, item_type in sorted(set(re.findall(r'(Page|Snapshot)<([A-Za-z][A-Za-z0-9]*)>', json.dumps(spec)))):
    target = f'{generic}<{item_type}>'
    name = f'{generic}Of{item_type}'
    closure = {generic: generic_shapes[generic]}
    pending = [item_type, 'Revision']
    while pending:
        item = pending.pop()
        if item in closure: continue
        if item in spec['models']:
            closure[item] = spec['models'][item]
            for field in closure[item]: pending.extend(re.findall(r'[A-Za-z][A-Za-z0-9]*', field['type']))
        elif item in spec['enums']: closure[item] = spec['enums'][item]
    fingerprint = hashlib.sha256(json.dumps({'root':target,'types':closure,'codec':'nexa-abi-value-1','scalarContract':1}, sort_keys=True, separators=(',',':')).encode()).hexdigest()
    schema_targets[name] = target
    schema_fingerprints[name] = fingerprint
    schemas += f'    public static SchemaRef {name} {{ get; }} = new(new("nexa:abi100/{name.lower()}"), 1, "{fingerprint}");\n'
schemas += '    public static bool Validate(SchemaRef schema, AbiValue value)\n    {\n        try\n        {\n            DataCodec.Validate(value);\n            switch (schema.Id.Value)\n            {\n'
for name, target in schema_targets.items():
    schemas += f'                case "nexa:abi100/{name.lower()}": if (schema != {name}) return false; _ = global::Nexa.Plugin.Sdk.Abi100.Data.{target}.Read(value); return true;\n'
schemas += '                default: return false;\n            }\n        }\n        catch (Exception error) when (error is FormatException or ArgumentException or OverflowException) { return false; }\n    }\n}\n'

parser=argparse.ArgumentParser();parser.add_argument('--verify',action='store_true');args=parser.parse_args()
outputs={'Models.g.cs':models,'Abilities.g.cs':apis,'Context.g.cs':context,'Catalog.g.cs':catalog,'Schemas.g.cs':schemas}
for name,body in outputs.items():
    body = body.rstrip() + '\n'
    path=SDK/'Generated'/name
    if args.verify:
        if not path.exists() or path.read_text()!=body: raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}')
    else:
        path.parent.mkdir(exist_ok=True);path.write_text(body)
guest = '/* Generated from contracts/abi100.json. SDK-local IDs, not transport opcodes. */\n#ifndef NEXA_ABI100_IDS_H\n#define NEXA_ABI100_IDS_H\n'
def macro(name): return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', name).replace('.', '_').upper()
for group in spec['groups']:
    prefix = 'NEXA_' + macro(group['name'])
    guest += f'#define {prefix}_CONTRACT "{group["contractId"]}"\n'
    for operation in group['operations']:
        guest += f'#define {prefix}_{macro(operation["name"])} {operation["methodId"]}u\n'
guest += '#endif\n'
guest_path = ROOT / 'sdk/wasm/include/nexa/abi100_ids.h'
if args.verify:
    if not guest_path.exists() or guest_path.read_text() != guest: raise SystemExit('Stale guest dispatch constants')
else:
    guest_path.parent.mkdir(parents=True, exist_ok=True); guest_path.write_text(guest)
from guest_bindings import generate as generate_guest_bindings
legacy = json.loads((ROOT / 'contracts/abi100-legacy.json').read_text())
guest_spec = dict(spec, models=spec['models'] | legacy['models'], groups=spec['groups'] + legacy['groups'])
bindings, conformance = generate_guest_bindings(guest_spec, schema_fingerprints)
for relative, body in [('sdk/wasm/include/nexa/abi100.h', bindings), ('tests/wasm/conformance.c', conformance)]:
    destination = ROOT / relative
    if args.verify:
        if not destination.exists() or destination.read_text() != body: raise SystemExit(f'Stale generated file: {relative}')
    else:
        destination.parent.mkdir(parents=True, exist_ok=True); destination.write_text(body)
print(f'ABI 100: {len(spec["models"])} models, {len(spec["groups"])} groups, {len(seen)} draft operations; generated files '+('verified' if args.verify else 'updated'))
